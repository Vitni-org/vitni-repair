create extension if not exists pgcrypto;

create table if not exists public.guides (
  id bigint generated by default as identity primary key,
  slug text unique,
  share_token text unique,
  match_key text,
  title text not null,
  description text not null default '',
  area text not null default 'Home' check (area in ('Bike', 'Home', 'Clothes', 'Other')),
  level text not null default 'Easy' check (level in ('Easy', 'Moderate', 'Advanced')),
  estimated_time text not null default '',
  confidence smallint not null default 0 check (confidence between 0 and 100),
  safety text not null check (safety in ('safe_diy', 'get_help', 'do_not_attempt')),
  safety_notes text not null default '',
  tools text[] not null default '{}',
  cover_path text not null default '',
  cover_alt text not null default '',
  source text not null check (source in ('curated', 'generated')),
  status text not null default 'draft' check (status in ('draft', 'published', 'needs_illustrations')),
  visibility text not null default 'public' check (visibility in ('public', 'unlisted')),
  search_vector tsvector not null default ''::tsvector,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((visibility = 'public' and slug is not null and share_token is null) or (visibility = 'unlisted' and slug is null and share_token is not null))
);

create unique index if not exists guides_match_key_unique
  on public.guides (match_key) where match_key is not null and visibility = 'public';
create index if not exists guides_public_created_idx
  on public.guides (created_at desc, id desc) where status in ('published', 'needs_illustrations') and visibility = 'public';
create index if not exists guides_search_vector_idx on public.guides using gin (search_vector);

create or replace function public.touch_guide_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists guides_updated_at on public.guides;
create trigger guides_updated_at before update on public.guides
for each row execute function public.touch_guide_updated_at();

create or replace function public.refresh_guide_search_vector()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.search_vector :=
    setweight(to_tsvector('simple', coalesce(new.title, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(new.description, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(new.area, '') || ' ' || array_to_string(new.tools, ' ')), 'C') ||
    setweight(to_tsvector('simple', coalesce((select string_agg(title || ' ' || instruction, ' ') from public.guide_steps where guide_id = new.id), '')), 'D') ||
    setweight(to_tsvector('simple', coalesce((select string_agg(name || ' ' || details, ' ') from public.guide_parts where guide_id = new.id), '')), 'D');
  return new;
end;
$$;

drop trigger if exists guides_search_vector_update on public.guides;
create trigger guides_search_vector_update
before insert or update of title, description, area, tools on public.guides
for each row execute function public.refresh_guide_search_vector();

create table if not exists public.guide_steps (
  id bigint generated by default as identity primary key,
  guide_id bigint not null references public.guides(id) on delete cascade,
  ordinal smallint not null check (ordinal between 1 and 8),
  title text not null,
  instruction text not null,
  illustration_path text,
  illustration_alt text not null default '',
  illustration_status text not null default 'pending' check (illustration_status in ('pending', 'ready', 'failed')),
  video_path text,
  video_status text check (video_status is null or video_status in ('pending', 'ready', 'failed')),
  unique (guide_id, ordinal)
);
create index if not exists guide_steps_guide_id_idx on public.guide_steps(guide_id);

create or replace function public.refresh_parent_guide_search_vector()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  parent_id bigint := coalesce(new.guide_id, old.guide_id);
begin
  update public.guides as g set title = g.title where g.id = parent_id;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
drop trigger if exists guide_steps_search_update on public.guide_steps;
create trigger guide_steps_search_update after insert or update or delete on public.guide_steps
for each row execute function public.refresh_parent_guide_search_vector();

create table if not exists public.guide_parts (
  id bigint generated by default as identity primary key,
  guide_id bigint not null references public.guides(id) on delete cascade,
  ordinal smallint not null check (ordinal between 1 and 12),
  name text not null,
  details text not null default '',
  retailer text,
  url text,
  unique (guide_id, ordinal)
);
create index if not exists guide_parts_guide_id_idx on public.guide_parts(guide_id);
drop trigger if exists guide_parts_search_update on public.guide_parts;
create trigger guide_parts_search_update after insert or update or delete on public.guide_parts
for each row execute function public.refresh_parent_guide_search_vector();

