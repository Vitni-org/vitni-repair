create table if not exists public.guide_scout_runs (
  id text primary key check (char_length(id) between 1 and 120),
  scheduled_at timestamptz not null,
  completed_at timestamptz,
  status text not null default 'researching'
    check (status in ('researching', 'drafted', 'skipped', 'failed')),
  topic text check (topic is null or char_length(topic) <= 240),
  primary_keyword text check (primary_keyword is null or char_length(primary_keyword) <= 160),
  related_keywords text[] not null default '{}',
  demand_evidence text check (demand_evidence is null or char_length(demand_evidence) <= 1200),
  guide_slug text,
  result_note text check (result_note is null or char_length(result_note) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists guide_scout_runs_created_idx
  on public.guide_scout_runs (created_at desc);
create index if not exists guide_scout_runs_status_created_idx
  on public.guide_scout_runs (status, created_at desc);

create or replace function public.touch_guide_scout_run_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists guide_scout_runs_updated_at on public.guide_scout_runs;
create trigger guide_scout_runs_updated_at before update on public.guide_scout_runs
for each row execute function public.touch_guide_scout_run_updated_at();
revoke all on function public.touch_guide_scout_run_updated_at() from public, anon, authenticated;
grant execute on function public.touch_guide_scout_run_updated_at() to service_role;

alter table public.guides
  add column if not exists scout_run_id text
  references public.guide_scout_runs(id) on delete set null;

create unique index if not exists guides_scout_run_unique
  on public.guides (scout_run_id) where scout_run_id is not null;

create table if not exists public.guide_research_sources (
  id bigint generated by default as identity primary key,
  run_id text not null references public.guide_scout_runs(id) on delete cascade,
  guide_id bigint not null references public.guides(id) on delete cascade,
  ordinal smallint not null check (ordinal between 1 and 10),
  title text not null check (char_length(title) between 1 and 300),
  url text not null check (url ~ '^https://'),
  publisher text not null default '' check (char_length(publisher) <= 200),
  created_at timestamptz not null default now(),
  unique (guide_id, url),
  unique (run_id, ordinal)
);

create index if not exists guide_research_sources_guide_id_idx
  on public.guide_research_sources (guide_id, ordinal);
create index if not exists guide_research_sources_run_id_idx
  on public.guide_research_sources (run_id);

alter table public.guide_scout_runs enable row level security;
alter table public.guide_research_sources enable row level security;

revoke all on public.guide_scout_runs, public.guide_research_sources from anon, authenticated;
grant select, insert, update on public.guide_scout_runs, public.guide_research_sources to service_role;
grant usage, select on sequence public.guide_research_sources_id_seq to service_role;

